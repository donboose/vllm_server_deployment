#!/usr/bin/env bash

# Install the dsh-web-search-searxng provider into a dsh profile on THIS
# machine and pin the web seam to it. Idempotent — safe to re-run.
#
#   ./install_dsh_web_search.sh                     # shared SearXNG (10.1.45.74:8888)
#   SEARXNG_URL=http://10.1.45.74:9000 ./install_dsh_web_search.sh
#
# Env:
#   SEARXNG_URL   SearXNG base URL, no trailing path (default http://10.1.45.74:8888)
#   DSH_PROFILE   dsh profile name (default web, i.e. `dsh web`)
#   DSH_HOME      dsh home dir (default: $DSH_HOME or ~/.dsh)
#
# What it does:
#   1. locates the dsh installation and its runtime version
#   2. copies ./dsh-web-search-searxng into <profile>/plugins/ and pins the
#      @deepseek-ai/dsh-web peer to the local runtime version
#   3. runs `dsh plugin <profile> add` (pnpm link dependency)
#   4. upserts a managed block into <profile>/cordis.patch.yml (provider
#      entry + web.searchProvider pin); the block is between the
#      `# >>> dsh-web-search-searxng` / `# <<< dsh-web-search-searxng` markers
#   5. verifies the composed tree via `dsh --dump-config`
#
# Requires: dsh, pnpm, node on PATH.

set -euo pipefail
PROJECT_ROOT="$(cd "$(dirname "$0")" && pwd)"
die() { echo "ERROR: $*" >&2; exit 1; }

SEARXNG_URL="${SEARXNG_URL:-http://10.1.45.74:8888}"
PROFILE="${DSH_PROFILE:-web}"
DSH_HOME="${DSH_HOME:-$HOME/.dsh}"
PROFILE_DIR="$DSH_HOME/profiles/$PROFILE"
PLUGIN_SRC="$PROJECT_ROOT/dsh-web-search-searxng"
PLUGIN_DST="$PROFILE_DIR/plugins/dsh-web-search-searxng"
PATCH_FILE="$PROFILE_DIR/cordis.patch.yml"

# --- 0. prerequisites ---
command -v dsh   >/dev/null 2>&1 || die "dsh not found on PATH"
command -v pnpm  >/dev/null 2>&1 || die "pnpm not found on PATH (required by dsh plugin)"
command -v node  >/dev/null 2>&1 || die "node not found on PATH"
[ -f "$PROFILE_DIR/package.json" ] || die "profile not found at $PROFILE_DIR (check DSH_PROFILE; `ps aux | grep dsh`)"
[ -f "$PLUGIN_SRC/lib/index.js" ] || die "plugin source missing at $PLUGIN_SRC"

# --- 1. locate dsh install + runtime version ---
DSH_BIN="$(readlink -f "$(command -v dsh)")"
INSTALL_DIR="$(dirname "$(dirname "$DSH_BIN")")"
[ -f "$INSTALL_DIR/package.json" ] || die "cannot locate dsh install dir from $DSH_BIN"
DSH_VERSION="$(node -p "require('$INSTALL_DIR/package.json').version")"
echo "dsh runtime: $DSH_VERSION ($INSTALL_DIR)"
echo "profile:     $PROFILE ($PROFILE_DIR)"
echo "searxng:     $SEARXNG_URL"

# --- 2. copy plugin + pin the dsh-web peer to the runtime version ---
mkdir -p "$PROFILE_DIR/plugins"
rm -rf "$PLUGIN_DST"
cp -R "$PLUGIN_SRC" "$PLUGIN_DST"
node - "$PLUGIN_DST/package.json" "$DSH_VERSION" <<'EOF'
const fs = require("fs");
const [file, version] = [process.argv[2], process.argv[3]];
const manifest = JSON.parse(fs.readFileSync(file, "utf8"));
if (manifest.peerDependencies["@deepseek-ai/dsh-web"] !== version) {
  manifest.peerDependencies["@deepseek-ai/dsh-web"] = version;
  fs.writeFileSync(file, JSON.stringify(manifest, null, 2) + "\n");
  console.log(`pinned @deepseek-ai/dsh-web peer to runtime version ${version}`);
}
EOF

# --- 3. install into the profile (relative path is anchored to the cwd) ---
cd "$PROFILE_DIR"
dsh plugin --profile "$PROFILE" add ./plugins/dsh-web-search-searxng
# Expected/benign: pnpm "linked in dependency will not resolve the peer
# dependencies" (the DSH runtime resolves those from the installation) and
# "declares no dsh.bundle — installed as a plain dependency".

# --- 4. upsert the managed block in cordis.patch.yml ---
FETCH_PROVIDER="$(dsh --profile "$PROFILE" --dump-config 2>/dev/null \
  | grep -A4 "^- id: web$" | grep -m1 "fetchProvider:" | awk '{print $2}' || true)"
FETCH_PROVIDER="${FETCH_PROVIDER:-http}"
node - "$PATCH_FILE" "$SEARXNG_URL" "$FETCH_PROVIDER" <<'EOF'
const fs = require("fs");
const [file, url, fetchProvider] = [process.argv[2], process.argv[3], process.argv[4]];
const BEGIN = "# >>> dsh-web-search-searxng: managed block, regenerated by install_dsh_web_search.sh";
const END = "# <<< dsh-web-search-searxng";
const block = [
  BEGIN,
  "# Self-hosted SearXNG search provider (keyless, free) for the web seam.",
  "- insert:",
  "    - id: web-search-searxng",
  '      name: "dsh-web-search-searxng"',
  "      config:",
  `        searxngUrl: "${url}"`,
  "        useDuckDuckGoFallback: true",
  "# Pin the web seam to the SearXNG provider. The override replaces the",
  "# entry's config wholesale, so the fetch provider must be restated.",
  "- id: web",
  '  name: "@deepseek-ai/dsh-web"',
  "  config:",
  "    searchProvider: searxng",
  `    fetchProvider: ${fetchProvider}`,
  END
];
let lines;
try {
  lines = fs.readFileSync(file, "utf8").split("\n");
} catch {
  lines = [];
}
const si = lines.findIndex((l) => l === BEGIN);
const ei = lines.findIndex((l) => l === END);
if (si !== -1) {
  if (ei === -1 || ei < si) {
    console.error("begin marker without a matching end marker; fix the patch file and re-run");
    process.exit(1);
  }
  lines.splice(si, ei - si + 1, ...block);
  console.log("replaced existing managed block");
} else if (lines.some((l) => l.includes("web-search-searxng"))) {
  console.error("found 'web-search-searxng' entries without the managed markers; remove them manually and re-run");
  process.exit(1);
} else {
  if (lines.length > 0 && lines[lines.length - 1] !== "") lines.push("");
  lines.push(...block, "");
  console.log("appended managed block");
}
fs.writeFileSync(file, lines.join("\n"));
EOF

# --- 5. verify the composed tree ---
DUMP="$(dsh --profile "$PROFILE" --dump-config 2>&1)"
grep -q "id: web-search-searxng" <<<"$DUMP" || die "verification failed: web-search-searxng missing from composed tree"
grep -q "searchProvider: searxng" <<<"$DUMP" || die "verification failed: web.searchProvider not pinned to searxng"
grep -q "id: web-search-searxng" <<<"$DUMP" \
  && ! grep -iqE "patch.*web-search-searxng" <<<"$DUMP" \
  || die "verification failed: patch warnings for web-search-searxng: $DUMP"

cat <<EOF

Installed. Next steps:
  1. If web_search still errors in the running GUI, fully quit and restart
     \`dsh web\` (profile changes usually hot-reload; a new package sometimes
     needs a restart; the session resumes after).
  2. Test: ask the agent to use its web_search tool — expect structured
     sources, and no "no API key for DEEPSEEK_API_KEY" error.

Rollback:
  - delete the managed block in $PATCH_FILE
    (between the '# >>> dsh-web-search-searxng' / '# <<<' markers)
  - dsh plugin --profile $PROFILE remove dsh-web-search-searxng
  - rm -rf $PLUGIN_DST
EOF
